import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { AppConfig } from '../config/config';

/**
 * Provider abstraction for file storage. `local` is for development, tests and single-instance staging.
 * An S3-compatible adapter is required before production (the config refuses `local` there).
 */
export interface StorageProvider {
  readonly key: string;
  put(storageKey: string, body: Buffer, contentType: string): Promise<void>;
  get(storageKey: string): Promise<Buffer | null>;
  delete(storageKey: string): Promise<void>;
}

export const STORAGE_PROVIDER = Symbol('STORAGE_PROVIDER');

export class LocalDiskStorage implements StorageProvider {
  readonly key = 'local';
  private readonly root: string;

  constructor(root: string) {
    this.root = path.resolve(root);
  }

  private resolve(storageKey: string): string {
    // Keys are generated by the server, but never let one escape the storage root.
    if (!/^[a-z0-9/_-]+\.[a-z0-9]+$/i.test(storageKey) || storageKey.includes('..')) throw new Error('Invalid storage key');
    return path.join(this.root, storageKey);
  }

  async put(storageKey: string, body: Buffer): Promise<void> {
    const file = this.resolve(storageKey);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, body);
  }

  async get(storageKey: string): Promise<Buffer | null> {
    try {
      return await readFile(this.resolve(storageKey));
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code === 'ENOENT') return null;
      throw err;
    }
  }

  async delete(storageKey: string): Promise<void> {
    await rm(this.resolve(storageKey), { force: true });
  }
}

export function createStorageProvider(config: AppConfig): StorageProvider {
  return new LocalDiskStorage(config.MEDIA_LOCAL_DIR);
}
